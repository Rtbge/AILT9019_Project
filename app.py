CEFR_DISCLAIMER = (
    "The CEFR estimate is approximate and generated by an AI model. "
    "It is not an official CEFR assessment."
)

REFUSAL_MARKERS = (
    "does not appear to be english",
    "input text is empty",
    "input is too short",
    "input is too long",
    "invalid cefr level",
)

_MD_SPECIAL = re.compile(r"([\\`*_{}\[\]()#+\-.!|>])")

