"""Streamlit interface for the AILT9019 English Grammar Assistant.

Person 2 final frontend. The app talks to Person 1's backend through the
stable ``analyze_text(text, cefr_level=None) -> dict`` contract documented in
INTEGRATION.md. Every backend field is read with ``.get()`` so a future
backend that adds fields cannot break the interface.

Set AILT9019_OFFLINE_DEMO=1 to run the interface against a clearly labelled
offline sample response. This is for teaching/demo evidence when the AI
provider is unavailable; it is never presented as live model inference.
"""

