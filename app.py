import html
import logging
import os
import re

import streamlit as st

from analyzer import analyze_text

logger = logging.getLogger(__name__)

MAX_TEXT_LENGTH = 1000

CEFR_OPTIONS = [
    "Not sure (let the tool decide)",
    "A1", "A2", "B1", "B2", "C1", "C2",
]

UNDERSTAND = "Understand a text I found"
