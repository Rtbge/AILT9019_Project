def friendly_error(message: str) -> str:
    """Explain known provider failures without displaying raw API diagnostics."""
    if not message.startswith("API call failed:"):
        return message
    if "AccessDenied.Unpurchased" in message:
        return (
            "The AI provider has not enabled model access for this account. "
            "Complete Model Studio activation and any required account verification "
            "in the region matching your API key. If this persists, contact provider support. "
            "Reference: AccessDenied.Unpurchased."
        )
    if "401" in message or "AuthenticationError" in message or "InvalidApiKey" in message:
        return "The AI provider could not authenticate the API key. Check the key and its matching regional endpoint."
    if "403" in message or "PermissionDenied" in message or "AccessDenied" in message:
        return "This account or workspace does not have permission to use the selected model. Check model access with your provider."
    if "429" in message or "RateLimit" in message:
        return "The AI provider reports a usage or rate limit. Check your quota and billing status before trying again."
    if "404" in message or "model_not_found" in message:
        return "The selected model or API endpoint was not found. Check the model identifier and regional endpoint."
    if "Connection" in message or "connection" in message or "SSL" in message:
        return "Cannot connect to the AI provider. Check your internet connection, endpoint, and certificate configuration."
    if "Timeout" in message or "timeout" in message or "timed out" in message:
        return "The AI service took too long to respond. Please try again later."
    return "The AI service could not complete the request. Please try again later or check the API configuration."


def _text(value: object) -> str:
    """Return a safe string for any backend value, including None."""
    return "" if value is None else str(value)


def _is_refusal(message: str) -> bool:
    """Distinguish an explained input refusal from a technical service error."""
    lowered = message.lower()
    return any(marker in lowered for marker in REFUSAL_MARKERS)


def _refusal_guidance(message: str) -> str:
    lowered = message.lower()
    if "too long" in lowered:
        return (
            "This text is too long. Please shorten it to 1,000 characters or fewer, "
            "then try again."
        )
    if "too short" in lowered or "empty" in lowered:
        return "Please enter a full English sentence with at least a few words."
    if "invalid cefr" in lowered:
        return "Please choose a CEFR level from the list (A1 to C2) or leave it on 'Not sure'."
    return (
        "This text looks like it is not written mainly in English. "
        "The assistant only checks English text. Please enter an English sentence "
        "or short paragraph and try again."
    )


def _highlight_changes(original: str, corrected: str) -> str:
    """Build escaped, inline-highlighted text showing removed and added words.

    Uses a token diff rather than model-supplied HTML, so no untrusted markup
    can reach the page. Removed wording is struck through; new wording is
    highlighted and underlined.
    """
    before = original.split()
    after = corrected.split()
    matcher = difflib.SequenceMatcher(None, before, after, autojunk=False)
    pieces: list[str] = []
    removed_style = (
        "background:#FCEBEB;color:#A32D2D;text-decoration:line-through;"
        "padding:1px 3px;border-radius:4px;"
    )
    added_style = (
        "background:#EAF3DE;color:#3B6D11;text-decoration:underline;"
        "padding:1px 3px;border-radius:4px;"
    )
    for tag, i1, i2, j1, j2 in matcher.get_opcodes():
        if tag == "equal":
            pieces.append(html.escape(" ".join(before[i1:i2])))
        else:
            if i2 > i1:
                pieces.append(
                    f'<del style="{removed_style}">{html.escape(" ".join(before[i1:i2]))}</del>'
                )
            if j2 > j1:
                pieces.append(
                    f'<ins style="{added_style}">{html.escape(" ".join(after[j1:j2]))}</ins>'
                )
    return " ".join(piece for piece in pieces if piece)


def _show_corrections(result: dict, original: str) -> None:
    corrected = _text(result.get("corrected_text"))
    errors = result.get("errors") or []
    st.subheader("Corrected text")
    st.text(corrected)

    if original != corrected and corrected:
        st.caption("Crossed-out words were removed. Underlined words are the suggested wording.")
        st.markdown(
            '<div style="font-size:15px;line-height:1.9;padding:12px 14px;'
            'border:1px solid #e3e3e3;border-radius:8px;overflow-wrap:anywhere;">'
            + _highlight_changes(original, corrected)
            + "</div>",
            unsafe_allow_html=True,
        )

    st.subheader("Grammar feedback")
    if not errors:
        if original == corrected:
            st.success("The analyser found no grammar mistakes in this text.")
        else:
            st.info("The analyser did not explain any specific corrections.")
        return

    count = len(errors)
    st.info(f"{count} grammar {'issue' if count == 1 else 'issues'} found.")
    for number, error in enumerate(errors, start=1):
        with st.container(border=True):
            st.write(f"Correction {number}")
            st.caption("Original wording")
            st.text(_text(error.get("original")))
            st.caption("Suggested correction")
            st.text(_text(error.get("corrected")))
            st.caption("Why this changed")
            st.text(_text(error.get("explanation")))


def _show_language_notes(result: dict) -> None:
    st.subheader("Grammar notes")
    explanations = result.get("grammar_explanations") or []
    if explanations:
        for explanation in explanations:
            st.text(_text(explanation))
    else:
        st.caption("No grammar notes were returned for this text.")

    st.subheader("Vocabulary")
    vocabulary = result.get("vocabulary") or []
    if vocabulary:
        for item in vocabulary:
            st.text(f"{_text(item.get('word'))} — {_text(item.get('meaning'))}")
    else:
        st.caption("No vocabulary entries were returned for this text.")

    st.subheader("CEFR Estimate")
    cefr_estimate = result.get("cefr_estimate")
    if cefr_estimate:
        st.metric("Approximate level", _text(cefr_estimate))
    else:
        st.caption("No CEFR estimate was returned for this text.")
    st.info(_text(result.get("cefr_note")) or CEFR_DISCLAIMER)


