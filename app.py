st.set_page_config(page_title="English Grammar Assistant", page_icon="📘", layout="centered")

OFFLINE_DEMO = os.getenv("AILT9019_OFFLINE_DEMO") == "1"

st.title("English Grammar Assistant")
st.write(
    "Paste a short English text and get a corrected version, plain-English "
    "grammar notes, useful vocabulary and an approximate difficulty level."
)
if OFFLINE_DEMO:
    st.warning(
        "OFFLINE DEMO MODE — choose a task to see its fixed sample and example feedback. "
        "No AI request is made."
    )

use_case = st.radio(
    "What would you like to do?",
    [UNDERSTAND, MY_WRITING],
    help="Both options use the same analysis engine; the difference is what the results page explains first.",
)

if use_case == MY_WRITING:
    st.write(
        "**Check my own writing** — paste something you wrote. We show a corrected "
        "version, highlight the words that changed, explain each mistake in simple "
        "English, and list useful vocabulary."
    )
else:
    st.write(
        "**Understand a text I found** — paste a correct sentence or a short paragraph "
        "from a book, lyric or article. We explain its grammar, useful vocabulary and "
        "rough difficulty (CEFR estimate), even when there are no mistakes."
    )

sample = OFFLINE_SAMPLES[use_case] if OFFLINE_DEMO else None
with st.form("grammar_form"):
    if sample:
        st.caption("This example is fixed. To enter your own text, start the app in live mode.")
    else:
        st.caption(
            "Paste an English sentence or short paragraph. Keep it within 1,000 characters "
            "and leave out personal information."
        )
    user_text = st.text_area(
        "English text",
        value=sample["original_text"] if sample else "",
        height=180,
        max_chars=MAX_TEXT_LENGTH,
        key=use_case if sample else "grammar_input",
        disabled=OFFLINE_DEMO,
    )
    cefr_choice = CEFR_OPTIONS[0]
    if not OFFLINE_DEMO:
        cefr_choice = st.selectbox(
            "Your English level (optional)",
            CEFR_OPTIONS,
            help="A1–C2 help tailor the explanations. Choose 'Not sure' if you do not know your level.",
        )
    submitted = st.form_submit_button("Show example feedback" if sample else "Analyse", type="primary")

if submitted:
    # A new submission replaces previous feedback, including on validation failure.
    st.session_state.pop("analysis", None)
    st.session_state.pop("analysed_text", None)
    st.session_state.pop("use_case", None)
    cleaned_text = (sample["original_text"] if sample else user_text).strip()
    if not cleaned_text:
        st.warning("Please enter an English sentence or short paragraph.")
    elif len(cleaned_text) < 2 or not any(character.isalpha() for character in cleaned_text):
        st.warning("Please enter an English sentence containing words.")
    elif len(cleaned_text) > MAX_TEXT_LENGTH:
        st.warning("Please shorten your text to 1,000 characters or fewer.")
    else:
        cefr_level = None if cefr_choice == CEFR_OPTIONS[0] else cefr_choice
        try:
            if sample:
                result = sample
            else:
                with st.spinner("Analysing your text…"):
                    result = analyze_text(cleaned_text, cefr_level=cefr_level)
            if not result.get("success"):
                # The backend's API error may contain provider details; use a friendly message.
                message = _text(result.get("message", "Analysis could not be completed. Please try again."))
                if _is_refusal(message):
                    st.warning(_refusal_guidance(message))
                else:
                    st.error(friendly_error(message))
            else:
                st.session_state["analysis"] = result
                st.session_state["analysed_text"] = cleaned_text
                st.session_state["use_case"] = use_case
        except Exception:
            logger.exception("Grammar analysis could not be completed")
            st.error("Analysis could not be completed. Please try again or ask the team to check the backend.")

# ---------------------------------------------------------------------------
# Results
# ---------------------------------------------------------------------------

result_mode = st.session_state.get("use_case", UNDERSTAND)
if "analysis" in st.session_state and (not OFFLINE_DEMO or result_mode == use_case):
    result = st.session_state["analysis"]
    original = st.session_state.get("analysed_text", _text(result.get("original_text")))
    st.divider()
    st.header("Your writing check" if result_mode == MY_WRITING else "Your reading guide")
    st.subheader("Your original text")
    st.text(original)

    if result_mode == MY_WRITING:
        _show_corrections(result, original)
        _show_language_notes(result)
    else:
        _show_language_notes(result)
        _show_corrections(result, original)

